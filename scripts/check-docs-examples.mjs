#!/usr/bin/env node
/**
 * Verifies the React and Vue docs examples the way a consumer would meet them:
 * against the BUILT packages (react/dist, vue/dist), not the sources.
 *
 *   1. Types. Generates an `All.tsx` / `All.vue` that imports every file under
 *      `<pkg>/docs-examples/`, then runs `tsc --noEmit` / `vue-tsc --noEmit`
 *      (strict templates for Vue) with the package name mapped to dist. A wrong
 *      prop, event, v-model or slot name fails here.
 *   2. Mount. Writes a one-page consumer app (package stylesheet + Tailwind entry,
 *      package name resolved to dist), serves it with Vite on a private port
 *      (5342, DOCS_EXAMPLES_PORT overrides) and drives every example in Chromium
 *      through scripts/docs-examples/mount.spec.ts, which reuses `collectErrors`
 *      from examples/consumers/smoke-helpers.ts. Overlays (popover, sheet,
 *      alert dialog, menus, combobox) are opened and must become visible; any
 *      console error, framework warning or uncaught exception fails. Nothing is
 *      stubbed and no GPU message is ignored.
 *
 * A failure means the example is wrong, or the port is. Fix the example first;
 * if the example matches the Svelte behaviour and the port still refuses it,
 * file a ticket against the port instead of bending the snippet.
 *
 *   node scripts/check-docs-examples.mjs [--only react|vue] [--build] [--types-only] [--mount-only]
 *
 * dist is built once when missing; `--build` forces a rebuild. Scratch files
 * live under `<pkg>/node_modules/.cache/docs-examples/` and are never shipped.
 */
import { spawnSync } from "node:child_process";
import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const args = process.argv.slice(2);
const flag = (name) => args.includes(`--${name}`);
const option = (name) => {
	const at = args.indexOf(`--${name}`);
	return at === -1 ? undefined : args[at + 1];
};

const FRAMEWORKS = {
	react: { dir: join(repoRoot, "react"), pkg: "fancy-ui-react", ext: ".tsx", tsc: "tsc" },
	vue: { dir: join(repoRoot, "vue"), pkg: "fancy-ui-vue", ext: ".vue", tsc: "vue-tsc" },
};

const slugsOf = (fw) =>
	readdirSync(join(fw.dir, "docs-examples"), { withFileTypes: true })
		.filter((entry) => entry.isFile() && entry.name.endsWith(fw.ext))
		.map((entry) => entry.name.slice(0, -fw.ext.length))
		.sort();

const scratchOf = (fw) => join(fw.dir, "node_modules", ".cache", "docs-examples");

/** `icon-button` -> `IconButtonExample`, as the React files name their export. */
const exportNameOf = (fw, slug) => {
	const source = readFileSync(join(fw.dir, "docs-examples", slug + fw.ext), "utf8");
	const match = source.match(/export function (\w+)/);
	if (!match) throw new Error(`docs-examples/${slug}${fw.ext} has no \`export function\``);
	return match[1];
};

// ---------------------------------------------------------------- mount mode

/**
 * Writes a one-page consumer app into the scratch folder: it loads the package's
 * own stylesheet (`styles.css`) and Tailwind entry (`tailwind.css`) exactly as
 * the README tells a consumer to, and renders the example named by `?slug=`.
 * Resolution goes through the package name mapped to dist, never the sources.
 */
function writeConsumerApp(fw, name) {
	const app = join(scratchOf(fw), "app");
	mkdirSync(app, { recursive: true });
	const loaders = slugsOf(fw)
		.map(
			(slug) =>
				`\t${JSON.stringify(slug)}: () => import(${JSON.stringify(join(fw.dir, "docs-examples", slug + fw.ext))}),`
		)
		.join("\n");
	const entry = name === "react" ? "main.tsx" : "main.ts";

	writeFileSync(
		join(app, "index.html"),
		`<!doctype html><html lang="en"><head><meta charset="utf-8" /><meta name="viewport" content="width=device-width, initial-scale=1" /><title>docs-examples</title></head><body style="padding:48px"><div id="root"></div><script type="module" src="./${entry}"></script></body></html>\n`
	);
	writeFileSync(
		join(app, "app.css"),
		`@import "tailwindcss";\n@import "${fw.pkg}/tailwind.css";\n@source ${JSON.stringify(join(fw.dir, "docs-examples"))};\n`
	);

	const head = `// Generated by scripts/check-docs-examples.mjs. Do not edit.
import "${fw.pkg}/styles.css";
import "./app.css";

const loaders: Record<string, () => Promise<any>> = {
${loaders}
};
const slug = new URLSearchParams(location.search).get("slug") ?? "";
const root = document.getElementById("root")!;
const ready = () => document.body.setAttribute("data-example-ready", "");
const load = loaders[slug];
if (!load) throw new Error("no docs example named " + slug);
const mod = await load();
`;
	if (name === "react") {
		writeFileSync(
			join(app, entry),
			`${head}import { StrictMode } from "react";
import { createRoot } from "react-dom/client";

const Example = Object.values(mod).find((value) => typeof value === "function") as () => any;
createRoot(root).render(
	<StrictMode>
		<Example />
	</StrictMode>
);
requestAnimationFrame(() => requestAnimationFrame(ready));
`
		);
	} else {
		writeFileSync(
			join(app, entry),
			`${head}import { createApp } from "vue";

const app = createApp(mod.default);
// Vue reports warnings through console.warn; surface them as errors.
app.config.warnHandler = (message) => console.error("[vue warn] " + message);
app.mount(root);
requestAnimationFrame(() => requestAnimationFrame(ready));
`
		);
	}

	const plugin =
		name === "react"
			? `import react from "@vitejs/plugin-react";\nconst framework = react();`
			: `import vue from "@vitejs/plugin-vue";\nconst framework = vue();`;
	writeFileSync(
		join(app, "vite.config.mjs"),
		`// Generated by scripts/check-docs-examples.mjs. Do not edit.
import { defineConfig } from "vite";
import tailwindcss from "@tailwindcss/vite";
${plugin}

export default defineConfig({
	root: ${JSON.stringify(app)},
	configFile: false,
	plugins: [framework, tailwindcss()],
	resolve: {
		alias: [
			{ find: "${fw.pkg}/styles.css", replacement: ${JSON.stringify(join(fw.dir, "dist", "styles.css"))} },
			{ find: "${fw.pkg}/tailwind.css", replacement: ${JSON.stringify(join(fw.dir, "tailwind.css"))} },
			{ find: /^${fw.pkg}$/, replacement: ${JSON.stringify(join(fw.dir, "dist", "index.js"))} },
		],
		dedupe: ["react", "react-dom", "vue"],
	},
	optimizeDeps: { include: ${JSON.stringify(name === "react" ? ["react", "react-dom/client", "react/jsx-runtime", "react/jsx-dev-runtime"] : ["vue"])} },
	server: { fs: { strict: false }, hmr: false },
	build: { target: "esnext" },
});
`
	);
	return app;
}

/**
 * Drives the examples in Chromium through the spec in scripts/docs-examples,
 * which reuses `collectErrors` from the consumer smoke helpers. The private
 * port defaults to 5342; DOCS_EXAMPLES_PORT overrides it.
 */
function mountAll(fw, name) {
	const app = writeConsumerApp(fw, name);
	const run = spawnSync(
		"pnpm",
		[
			"exec",
			"playwright",
			"test",
			"--config",
			join(repoRoot, "scripts", "docs-examples", "playwright.config.ts"),
		],
		{
			cwd: repoRoot,
			stdio: "inherit",
			env: {
				...process.env,
				DOCS_EXAMPLES_APP_DIR: app,
				DOCS_EXAMPLES_CWD: fw.dir,
				DOCS_EXAMPLES_SLUGS: slugsOf(fw).join(","),
				DOCS_EXAMPLES_PORT: process.env.DOCS_EXAMPLES_PORT ?? "5342",
			},
		}
	);
	if (run.status !== 0) {
		console.error(`\n${fw.pkg}: docs examples failed in the browser mount`);
		process.exit(run.status ?? 1);
	}
}

// ------------------------------------------------------------------ type mode

function run(command, commandArgs, cwd) {
	const result = spawnSync(command, commandArgs, { cwd, encoding: "utf8", stdio: "pipe" });
	return { status: result.status, output: `${result.stdout ?? ""}${result.stderr ?? ""}` };
}

function ensureDist(name, fw) {
	if (flag("build") || !existsSync(join(fw.dir, "dist", "index.js"))) {
		console.log(`building ${fw.pkg} (dist missing or --build)`);
		const build = run("pnpm", ["--dir", fw.dir, "build"], repoRoot);
		if (build.status !== 0) {
			console.error(build.output);
			console.error(`${fw.pkg} build failed`);
			process.exit(1);
		}
	}
}

function writeScratch(fw) {
	const scratch = scratchOf(fw);
	mkdirSync(scratch, { recursive: true });
	const slugs = slugsOf(fw);
	const relExample = (slug) => `../../../docs-examples/${slug}${fw.ext}`;

	if (fw === FRAMEWORKS.react) {
		const lines = [
			"// Generated by scripts/check-docs-examples.mjs. Do not edit.",
			...slugs.map(
				(slug) =>
					`import { ${exportNameOf(fw, slug)} } from "${relExample(slug).replace(/\.tsx$/, "")}";`
			),
			"",
			"export const examples = [",
			...slugs.map((slug) => `\t<${exportNameOf(fw, slug)} key="${slug}" />,`),
			"];",
			"",
		];
		writeFileSync(join(scratch, "All.tsx"), lines.join("\n"));
	} else {
		const names = slugs.map(
			(slug) => slug.replace(/(^|-)(\w)/g, (_m, _d, c) => c.toUpperCase()) + "Example"
		);
		const lines = [
			"<!-- Generated by scripts/check-docs-examples.mjs. Do not edit. -->",
			'<script setup lang="ts">',
			...slugs.map((slug, i) => `import ${names[i]} from "${relExample(slug)}";`),
			"</script>",
			"",
			"<template>",
			...names.map((name) => `\t<${name} />`),
			"</template>",
			"",
		];
		writeFileSync(join(scratch, "All.vue"), lines.join("\n"));
	}

	const tsconfig = {
		compilerOptions: {
			target: "ES2022",
			lib: ["ES2022", "DOM", "DOM.Iterable"],
			module: "ESNext",
			moduleResolution: "bundler",
			jsx: "react-jsx",
			strict: true,
			noUncheckedIndexedAccess: true,
			verbatimModuleSyntax: true,
			isolatedModules: true,
			skipLibCheck: true,
			noEmit: true,
			types: [],
			baseUrl: "../../..",
			paths: { [fw.pkg]: ["./dist/index.d.ts"] },
		},
		...(fw === FRAMEWORKS.vue ? { vueCompilerOptions: { strictTemplates: true } } : {}),
		include: [
			fw === FRAMEWORKS.react ? "./All.tsx" : "./All.vue",
			`../../../docs-examples/**/*${fw.ext}`,
		],
		exclude: [],
	};
	writeFileSync(join(scratch, "tsconfig.json"), JSON.stringify(tsconfig, null, "\t"));
	return join(scratch, "tsconfig.json");
}

function typeCheck(fw) {
	const tsconfig = writeScratch(fw);
	const { status, output } = run("pnpm", ["exec", fw.tsc, "--noEmit", "-p", tsconfig], fw.dir);
	const lines = output.split("\n").filter((line) => /error TS\d+/.test(line));
	// Only diagnostics in the examples (or the generated barrel) count: dist
	// declarations are shipped output, checked by the package's own build.
	const own = lines.filter((line) => /docs-examples\/|All\.(tsx|vue)/.test(line));
	if (own.length > 0) {
		console.error(own.join("\n"));
		console.error(`\n${own.length} type error(s) in ${fw.pkg} docs-examples against dist`);
		process.exit(1);
	}
	if (status !== 0 && lines.length === 0) {
		console.error(output || `${fw.tsc} failed without diagnostics`);
		process.exit(1);
	}
	console.log(`${fw.pkg}: ${slugsOf(fw).length} example(s) type-check against dist`);
}

// ----------------------------------------------------------------------- main

const only = option("only");
const targets = Object.entries(FRAMEWORKS).filter(([name]) => !only || name === only);
if (targets.length === 0) {
	console.error("--only takes react or vue");
	process.exit(2);
}

for (const [name, fw] of targets) {
	ensureDist(name, fw);
	if (!flag("mount-only")) typeCheck(fw);
	if (!flag("types-only")) {
		mountAll(fw, name);
	}
}
console.log("docs-examples: every example type-checks against dist and mounts");
