#!/usr/bin/env node
/**
 * Generates nuxt/src/manifest.ts: the component export names of the
 * fancy-ui-vue ROOT barrel (the `fancy-ui-vue` specifier, never `/cameleon`).
 *
 * Source of truth: the BUILT barrel (`import("fancy-ui-vue")` → vue/dist/index.js),
 * filtered by runtime shape. An export is a component when it is a Vue component
 * object (has `setup`, `render` or `__name`). This is what the shims will actually
 * re-export, so the manifest can never list a name the package does not ship, and
 * non-components (`*_KEY` injection symbols, `BOOK_*` maps, presets, `toast`,
 * sound API, `cn`, …) drop out without a hand-kept deny list. Parsing vue/src would
 * duplicate the export resolution the bundler already did.
 *
 * Requires `pnpm --filter fancy-ui-vue build` to have run.
 *
 *   node scripts/generate-manifest.mjs          write src/manifest.ts
 *   node scripts/generate-manifest.mjs --check  exit 1 if src/manifest.ts is stale
 */
import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";

const MANIFEST = fileURLToPath(new URL("../src/manifest.ts", import.meta.url));

/** @param {unknown} value */
export function isVueComponent(value) {
	if (!value || (typeof value !== "object" && typeof value !== "function")) return false;
	const v = /** @type {Record<string, unknown>} */ (value);
	return (
		typeof v.setup === "function" || typeof v.render === "function" || typeof v.__name === "string"
	);
}

/** @param {Record<string, unknown>} mod */
export function componentExports(mod) {
	return Object.keys(mod)
		.filter((name) => /^[A-Z]/.test(name) && isVueComponent(mod[name]))
		.sort((a, b) => (a < b ? -1 : a > b ? 1 : 0));
}

/** @param {string[]} names */
export function renderManifest(names) {
	const body = names.map((n) => `\t"${n}",`).join("\n");
	return `// generated by scripts/generate-manifest.mjs — do not edit
// Component export names of the fancy-ui-vue root barrel (${names.length}).

export const components = [
${body}
] as const;

export type FancyComponentName = (typeof components)[number];
`;
}

async function main() {
	const mod = await import("fancy-ui-vue");
	const names = componentExports(mod);
	if (names.length === 0) throw new Error("no component exports found — is vue/dist built?");
	const next = renderManifest(names);

	if (process.argv.includes("--check")) {
		const current = await readFile(MANIFEST, "utf8").catch(() => "");
		if (current !== next) {
			console.error("src/manifest.ts is stale — run `node scripts/generate-manifest.mjs`.");
			process.exit(1);
		}
		console.log(`src/manifest.ts up to date (${names.length} components).`);
		return;
	}
	await writeFile(MANIFEST, next);
	console.log(`wrote src/manifest.ts (${names.length} components).`);
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
	await main();
}
